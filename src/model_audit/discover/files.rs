//! Preserve empty, excluded and malformed files instead of silently losing coverage.
use crate::model_audit::{parse, types::Model};
use serde::Serialize;
use std::path::{Path, PathBuf};

/// File discovery evidence, e.g. a parse error alongside a source-relative path.
#[derive(Debug, Serialize)]
pub(in crate::model_audit) struct SourceFile {
    pub path: PathBuf,
    pub status: String,
    pub declarations: Vec<String>,
    pub diagnostic: Option<String>,
    pub runtime_sql: Vec<super::runtime_sql::Finding>,
}

/// Read one source file without rewriting it or expanding macros.
pub(super) fn inspect(
    path: &Path,
    root: &Path,
    generated: Option<&Path>,
    models: &mut Vec<Model>,
    errors: &mut Vec<String>,
) -> SourceFile {
    let mut file = SourceFile {
        path: path.strip_prefix(root).unwrap_or(path).into(),
        status: "generated_excluded".into(),
        declarations: vec![],
        diagnostic: None,
        runtime_sql: vec![],
    };
    if Some(path) == generated {
        return file;
    }
    let result = std::fs::read_to_string(path)
        .map_err(|e| format!("{}: {e}", path.display()))
        .and_then(|source| {
            if source
                .lines()
                .take(5)
                .any(|line| line.contains("Generated by `rustyroad"))
            {
                return Ok(None);
            }
            file.runtime_sql = super::runtime_sql::scan(&source);
            file.status = "parse_error".into();
            parse::parse(path, root, &source).map(Some)
        });
    match result {
        Ok(Some(found)) => {
            file.status = if found.is_empty() {
                "no_declarations"
            } else {
                "parsed"
            }
            .into();
            file.declarations = found.iter().map(|model| model.id.clone()).collect();
            models.extend(found);
        }
        Ok(None) => (),
        Err(error) => {
            if file.status == "generated_excluded" {
                file.status = "read_error".into();
            }
            errors.push(error.clone());
            file.diagnostic = Some(error);
        }
    }
    file
}

/// Renders repositories; e.g. `render(schema)` adds unique-key policies to keyed CRUD.
/// # Examples
/// ```sh
/// rustyroad pull --language rust --out ./generated-db
/// ```
pub(super) fn render(schema: &Schema, names: &Names) -> String {
    render_with_relationship_reads(schema, names, true)
}

/// Controls only automatic relationship reads, preserving all table operations.
/// # Examples
/// ```sh
/// rustyroad pull --language rust --out ./generated-db
/// ```
pub(super) fn render_with_relationship_reads(
    schema: &Schema,
    names: &Names,
    relationship_reads: bool,
) -> String {
    let mut output =
        String::from("// Generated by `rustyroad pull --language rust`; do not edit.\n\n");
    let (body, needs_builder) = body::render(schema, names, relationship_reads);
    if body.is_empty() {
        return output;
    }
    if needs_builder {
        output.push_str("use sqlx::{PgPool, Postgres, QueryBuilder};\n\n");
    } else {
        output.push_str("use sqlx::PgPool;\n\n");
    }
    output.push_str("use super::models::*;\n\n");
    output.push_str(&clock::render());
    output.push_str(&read_snapshot::render());
    output.push_str(&body);
    output
}
